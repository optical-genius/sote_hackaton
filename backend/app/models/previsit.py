from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from .patient import MedicationItem, DiagnosisItem, AllergyItem

class PrevisitDraftRequest(BaseModel):
    patient_id: str
    service_id: str  # yleislaakari, fysioterapia, sosiaalipalvelut, neuvola
    initial_reason: str
    acting_as: str = "self"  # self | guardian

class PrevisitFormField(BaseModel):
    key: str
    label_fi: str
    label_sv: str
    label_en: str
    value: Optional[Any] = None
    is_filled: bool = False
    is_required: bool = True
    highlight: bool = False

class GapQuestionRequest(BaseModel):
    language: str = "fi"
    service_id: str
    current_reason: str
    filled_fields: Dict[str, Any]
    last_user_message: Optional[str] = None
    acting_as: str = "self"

class GapQuestionResponse(BaseModel):
    target_field: str
    question_text: str
    quick_replies: List[str] = Field(default_factory=list)
    selkokieli_tip: Optional[str] = None
    is_completed: bool = False

class ExtractEntitiesRequest(BaseModel):
    user_input: str
    target_field: Optional[str] = None
    language: str = "fi"
    current_data: Dict[str, Any] = Field(default_factory=dict)

class ExtractEntitiesResponse(BaseModel):
    extracted_fields: Dict[str, Any]
    feedback_message: str
    confidence: float = 0.95
    completed: bool = False

class TriageAnswer(BaseModel):
    """Structured answer to a single AI triage question."""
    question_id: str
    badge: str
    question_text: str
    answer_value: str
    answer_label: str
    is_red_flag: bool = False

class FinalSubmissionPayload(BaseModel):
    patient_id: str
    acting_as: str = "self"
    guardian_name: Optional[str] = None
    service_id: str
    language: str = "fi"
    reason_for_visit: str
    symptom_duration: Optional[str] = None
    pain_scale: Optional[int] = None
    accompanying_symptoms: List[str] = Field(default_factory=list)
    # Structured triage Q&A from AI-driven clinical questions
    ai_triage_answers: List[TriageAnswer] = Field(default_factory=list)
    impact_on_daily_life: Optional[str] = None
    confirmed_medications: List[MedicationItem] = Field(default_factory=list)
    confirmed_diagnoses: List[DiagnosisItem] = Field(default_factory=list)
    allergies: List[AllergyItem] = Field(default_factory=list)
    consent_given: bool = True
    ai_assisted_structuring: bool = True

class ClinicalSummaryResponse(BaseModel):
    submission_id: str
    created_at: str
    summary_markdown_fi: str
    summary_markdown_sv: str
    summary_markdown_en: str
    key_findings: List[str]
    red_flags: List[str]
    discrepancies: List[Dict[str, str]]
    validation_status: str
    patient_snapshot: Dict[str, Any]
    # Structured triage answers as-filled by patient (displayed first in doctor view)
    triage_structured: List[Dict[str, Any]] = Field(default_factory=list)
    # AI-generated clinical anamnesis (shown after patient data, generated by Medicus)
    medicus_anamnesis: Optional[str] = None
